const now = () => new Date().toISOString()

export const toBrief = (r: BriefRow, perImageUsd: number, seconds: number): ImageBrief => ({
  id: r.id,
  boardId: r.boardId,
  request: r.request,
  mode: r.mode,
  parentId: r.parentId,
  referenceIds: r.referenceIds,
  verdict: r.verdict,
  category: r.category,
  reason: r.reason,
  rightsSubject: r.rightsSubject,
  attestation: r.attestation,
  understanding: r.understanding,
  piece: r.piece,
  // Kept back until the person attests, so a brand prompt is never generated by accident.
  prompt: r.verdict === 'refuse' ? '' : r.prompt,
  aspect: r.aspect,
  provider: r.provider,
  model: r.model,
  estimate: { count: 4, perImageUsd, usd: perImageUsd * 4, seconds },
  claudeModel: r.claudeModel,
  claudeUsd: fromMicros(r.claudeMicros),
  decisions: r.decisions,
  generations: r.generations,
  createdAt: r.createdAt.toISOString(),
})

/** The brief as the person sees it, priced with its provider now. */
async function present(ctx: Ctx, row: BriefRow): Promise<ImageBrief> {
  let per = 0
  let seconds = 0
  try {
    const p = await ctx.services.get('imageGen').price(serviceContext(ctx), row.provider)
    per = p.perImageUsd
    seconds = p.provider.seconds
  } catch {
    // The provider's key was removed since: the brief still reads, unpriced.
  }
  return toBrief(row, per, seconds)
}

/** The board's project, which image spend counts against. */
const projectOf = (board: BoardRow) => board.pieceId ?? board.pinsFor

/** Claude for this command: the run's own client inside a run, else the organisation's default tier. */
async function claudeFor(ctx: Ctx, purpose: string): Promise<ClaudeCall> {
  if (ctx.claude) return ctx.claude
  const assistant = ctx.services.optional('assistant')
  if (!assistant?.claude || (assistant.available && !(await assistant.available(ctx.orgId))))
    throw new NotConfiguredError(
      'assistant',
      'Generating images needs a Claude API key too: Claude writes the prompt and checks every image before it is kept. An owner or admin can add one in Settings, AI.',
    )
  return assistant.claude(serviceContext(ctx), purpose)
}

/** One structured Claude call, metered whether or not its answer is usable (the tokens were spent). */
async function ask(
  ctx: Ctx,
  claude: ClaudeCall,
  params: BetaMessageStreamParams,
  suffix: string,
  board: BoardRow,
): Promise<{ message: BetaMessage; costUsd: number }> {
  let message: BetaMessage
  try {
    message = await claude.client
      .stream(params, ctx.signal ? { signal: ctx.signal } : {})
      .finalMessage()
  } catch (err) {
    if (ctx.signal?.aborted) throw ctx.signal.reason
    throw new AppError('conflict', mapError(err, { model: claude.model }).message)
  }
  const usage = messageUsage(message)
  await recordUsage(ctx, {
    meter: 'llm',
    provider: 'anthropic',
    model: message.model,
    quantity:
      usage.tokens.input + usage.tokens.output + usage.tokens.cacheRead + usage.tokens.cacheWrite,
    unit: 'tokens',
    costUsd: usage.costUsd,
    idempotencyKey: `${claude.key}:${suffix}`,
    runId: claude.runId,
    pieceId: projectOf(board),
    stage: 'design',
  })
  await claude.spent(usage.tokens, usage.costUsd)
  return { message, costUsd: usage.costUsd }
}

/** A board picture as Claude and the provider receive it: upright, at most 1568 px. */
async function picture(ctx: Ctx, ref: Reference, label: string) {
  if (!ref.assetId) throw badRequest(`“${ref.title || ref.id}” has no picture to work from`)
  const { asset, bytes } = await readAsset(ctx, ref.assetId)
  if (asset.kind !== 'image') throw badRequest(`“${ref.title || asset.name}” is not a picture`)
  const image = await modelImage(bytes, asset.mime)
  if (!image)
    throw badRequest(
      `“${ref.title || asset.name}” is a ${asset.mime} picture, which cannot be sent`,
    )
  const brief: BriefImage = { ...image, label }
  const provider: ProviderReference = {
    bytes: new Uint8Array(Buffer.from(image.data, 'base64')),
    mime: image.mediaType,
    title: ref.title || asset.name,
    role: null,
  }
  return { brief, provider }
}

interface Inputs {
  references: Reference[]
  parent: Reference | null
  /** Notes on the board named in the request go into the request as text. */
  notes: string[]
}

/**
 * The board items a request names, checked: they belong to the organisation, no view-only item
 * is sent to a model, roles name only those items, and vary or refine name a parent picture.
 */
async function inputsOf(
  ctx: Ctx,
  input: Pick<
    CommandParsedInput<'references.brief'>,
    'referenceIds' | 'roles' | 'mode' | 'parentId'
  >,
): Promise<Inputs> {
  const ids = [...new Set([...input.referenceIds, ...(input.parentId ? [input.parentId] : [])])]
  const rows = ids.length
    ? await ctx.repo.references.many({ where: inArray(t.reference.id, ids) })
    : []
  const missing = ids.filter((id) => !rows.some((r) => r.id === id))
  if (missing.length) throw notFound('Reference', missing[0])
  const stray = input.roles.find((r) => !input.referenceIds.includes(r.id))
  if (stray) throw badRequest(`A role was given for "${stray.id}", which is not among referenceIds`)
  const byId = new Map(rows.map((r) => [r.id, toReference(r)]))
  const viewOnly = [...byId.values()].filter((r) => r.rights === 'viewOnly')
  if (viewOnly.length)
    throw badRequest(
      `These references are view-only and cannot be sent to a generative model: ${viewOnly.map((r) => r.title || r.id).join(', ')}`,
    )
  if ((input.mode === 'vary' || input.mode === 'refine') && !input.parentId)
    throw badRequest(
      `To ${input.mode === 'vary' ? 'vary' : 'refine'} an image, name it as parentId`,
    )
  const parent = input.parentId ? byId.get(input.parentId)! : null
  if (parent && !parent.assetId) throw badRequest('The image to vary or refine has no picture')
  const references: Reference[] = []
  const notes: string[] = []
  // In the order asked for, so "reference 1" in a request is the first id given.
  for (const id of input.referenceIds) {
    const r = byId.get(id)!
    if (r.type === 'note') notes.push(r.note || r.title)
    else if (r.assetId) references.push(r)
    else
      throw badRequest(`“${r.title || r.id}” is a link without a picture; capture its image first`)
  }
  await assertSendable(
    ctx,
    [...references, ...(parent ? [parent] : [])].flatMap((r) => (r.assetId ? [r.assetId] : [])),
    (assetId) => references.find((r) => r.assetId === assetId)?.title ?? 'A picture',
  )
  return { references, parent, notes }
}

const labelOf = (r: Reference, i: number, role: string | undefined) =>
  `Reference ${i + 1}${role ? ` (${role})` : ''}: ${r.title || 'Untitled'}`

/** The reason a person reads: the guardrail's own sentence, then the rule it falls under. */
const reasonOf = (read: Pick<BriefRead, 'verdict' | 'category' | 'reason'>) =>
  read.verdict === 'allow' || !read.category
    ? read.reason
    : `${read.reason.trim()} ${GUARDRAIL_WORDS[read.category]}`.trim()

// ── references.brief ────────────────────────────────────────────────────────────────────────

export async function writeBrief(
  ctx: Ctx,
  input: CommandParsedInput<'references.brief'>,
): Promise<ImageBrief> {
  const board = await getBoard(ctx, input.boardId)
  // The provider decides how the prompt carries the references, so it is settled first; a board
  // with no usable provider is refused before anything is spent.
  const resolved = await ctx.services
    .get('imageGen')
    .resolve(serviceContext(ctx), input.provider ?? board.imageProvider ?? null)
  const inputs = await inputsOf(ctx, input)
  await assertBudget(ctx)
  const claude = await claudeFor(ctx, 'brief')

  const roleOf = (id: string) => input.roles.find((r) => r.id === id)?.role
  const references = await Promise.all(
    inputs.references.map((r, i) => picture(ctx, r, labelOf(r, i, roleOf(r.id)))),
  )
  const parent = inputs.parent ? await picture(ctx, inputs.parent, 'Parent image') : null
  const takesRefs =
    resolved.provider.models.find((m) => m.id === resolved.model)?.takesReferences ?? false
  const request = [input.request, ...inputs.notes.map((n) => `Note on the board: ${n}`)].join('\n')
  const id = createId('brf')
  const { message, costUsd } = await ask(
    ctx,
    claude,
    buildBriefRequest({
      model: claude.model,
      request,
      mode: input.mode,
      references: references.map((r) => r.brief),
      parent: parent?.brief ?? null,
      aspect: input.aspect,
      providerSeesReferences: takesRefs,
      attested: null,
    }),
    `${id}:brief`,
    board,
  )
  let read: BriefRead
  try {
    read = parseBriefMessage(message)
  } catch (err) {
    if (!(err instanceof GuardError)) throw err
    if (err.code === 'internal') throw conflict(err.message)
    // Claude itself declined to read the request: that is a refusal, recorded like any other.
    read = {
      verdict: 'refuse',
      category: 'other',
      reason: 'Claude declined to work on this request.',
      rightsSubject: null,
      understanding: input.request.slice(0, 200),
      piece: { kind: null, metal: null, stones: null, view: '' },
      prompt: '',
    }
  }
  // A verdict without a category, or a trademark refused outright, is read in the person's favour
  // only where the rules allow: needs_rights must name the trademark category.
  const category: GuardrailCategory | null =
    read.verdict === 'allow' ? null : (read.category ?? 'other')
  const verdict =
    read.verdict === 'needs_rights' && category !== 'trademark' ? 'refuse' : read.verdict
  const decision: GuardrailDecision = {
    stage: 'request',
    index: null,
    verdict,
    category,
    reason: read.reason,
    model: message.model,
    at: now(),
  }
  const row = await ctx.repo.imageBriefs.insert({
    id,
    boardId: board.id,
    userId: ctx.user.id,
    runId: claude.runId,
    request: input.request,
    mode: input.mode,
    parentId: input.parentId ?? null,
    referenceIds: inputs.references.map((r) => r.id),
    roles: input.roles,
    verdict,
    category,
    reason: reasonOf({ verdict, category, reason: read.reason }),
    rightsSubject: verdict === 'needs_rights' ? read.rightsSubject : null,
    attestation: null,
    understanding: read.understanding,
    piece: read.piece,
    prompt: verdict === 'refuse' ? '' : read.prompt,
    aspect: input.aspect,
    provider: resolved.provider.id,
    model: resolved.model,
    claudeModel: message.model,
    claudeMicros: toMicros(costUsd),
    decisions: [decision],
  })
  return toBrief(
    row,
    resolved.provider.perImageUsd(resolved.model, resolved.quality),
    resolved.provider.seconds,
  )
}

async function briefRow(ctx: Ctx, id: string): Promise<BriefRow> {
  const row = await ctx.repo.imageBriefs.first(eq(t.imageBrief.id, id))
  if (!row) throw notFound('Brief', id)
  return row
}

/** Appends decisions (and other changes) to a brief in one statement, so two writers both land. */
async function addDecisions(
  ctx: Ctx,
  id: string,
  decisions: GuardrailDecision[],
  patch: Partial<typeof t.imageBrief.$inferInsert> = {},
  extraUsd = 0,
): Promise<BriefRow> {
  const b = t.imageBrief
  const [row] = await ctx.repo.imageBriefs.update(eq(b.id, id), {
    ...patch,
    decisions: sql`${b.decisions} || ${JSON.stringify(decisions)}::jsonb`,
    claudeMicros: sql`${b.claudeMicros} + ${toMicros(extraUsd)}`,
  })
  if (!row) throw notFound('Brief', id)
  return row
}

// ── references.attestBrief ──────────────────────────────────────────────────────────────────

export async function attestBrief(
  ctx: Ctx,
  input: CommandParsedInput<'references.attestBrief'>,
): Promise<ImageBrief> {
  // A rights attestation is a person's statement; the assistant can never make it for them.
  if (ctx.actor.type !== 'user')
    throw forbidden('Only a person can attest the right to use a design')
  const row = await briefRow(ctx, input.id)
  if (row.verdict !== 'needs_rights')
    throw conflict(
      row.verdict === 'refuse'
        ? 'This request was refused, and attesting rights cannot change that.'
        : 'This request needs no attestation.',
    )
  const at = now()
  const updated = await addDecisions(
    ctx,
    row.id,
    [
      {
        stage: 'request',
        index: null,
        verdict: 'attested',
        category: 'trademark',
        reason: `${ctx.user.name || ctx.user.email || ctx.user.id} attested ${input.rights === 'own' ? 'owning' : input.rights === 'licensed' ? 'a licence for' : 'permission to use'} ${row.rightsSubject ?? 'the named design'}.`,
        model: null,
        at,
      },
    ],
    { attestation: { rights: input.rights, by: ctx.user.id, at } },
  )
  return present(ctx, updated)
}

// ── references.estimate ─────────────────────────────────────────────────────────────────────

export async function estimate(
  ctx: Ctx,
  input: CommandParsedInput<'references.estimate'>,
): Promise<CommandOutput<'references.estimate'>> {
  const board = await getBoard(ctx, input.boardId)
  const p = await ctx.services
    .get('imageGen')
    .price(serviceContext(ctx), input.provider ?? board.imageProvider ?? null)
  return {
    provider: p.provider.id,
    model: p.model,
    usd: p.perImageUsd * input.count,
    seconds: p.provider.seconds,
    count: input.count,
    perImageUsd: p.perImageUsd,
  }
}

// ── references.generate ─────────────────────────────────────────────────────────────────────

/** Whether a brief may generate now, and why not. */
export function blockedReason(
  row: Pick<BriefRow, 'verdict' | 'reason' | 'attestation'>,
): string | null {
  if (row.verdict === 'refuse') return row.reason
  if (row.verdict === 'needs_rights' && !row.attestation)
    return `${row.reason} Attest your right to use it to go on.`
  return null
}

function providerFailure(err: ProviderError, provider: ImageProvider): AppError {
  const fix =
    err.code === 'invalid' || err.code === 'forbidden'
      ? ' Check the key in Settings, AI.'
      : err.code === 'rate_limited' || err.code === 'unreachable'
        ? ' Nothing was kept; try again in a minute.'
        : ''
  return new AppError('conflict', `${err.message}${fix}`, { provider: provider.id, code: err.code })
}

export async function generate(
  ctx: Ctx,
  input: CommandParsedInput<'references.generate'>,
): Promise<CommandOutput<'references.generate'>> {
  let row = await briefRow(ctx, input.briefId)
  const blocked = blockedReason(row)
  if (blocked) throw conflict(blocked, { category: row.category })
  const board = await getBoard(ctx, row.boardId)
  const resolved = await ctx.services.get('imageGen').resolve(serviceContext(ctx), row.provider)
  const claude = await claudeFor(ctx, 'generate')
  const genId = createId('gen')
  const decisions: GuardrailDecision[] = []
  let claudeUsd = 0
  const attested = row.attestation ? row.rightsSubject : null

  // An edited prompt is checked again before anything is generated from it.
  const prompt = input.prompt?.trim() || row.prompt
  if (prompt !== row.prompt) {
    const { message, costUsd } = await ask(
      ctx,
      claude,
      buildBriefRequest({
        model: claude.model,
        request: row.request,
        mode: row.mode,
        references: [],
        parent: null,
        aspect: row.aspect,
        providerSeesReferences: true,
        attested,
        checkOnly: prompt,
      }),
      `${genId}:recheck`,
      board,
    )
    claudeUsd += costUsd
    let read: Pick<BriefRead, 'verdict' | 'category' | 'reason'>
    try {
      read = parseBriefMessage(message)
    } catch (err) {
      if (!(err instanceof GuardError)) throw err
      read = { verdict: 'refuse', category: 'other', reason: err.message }
    }
    const ok = read.verdict === 'allow' || (read.verdict === 'needs_rights' && !!attested)
    const decision: GuardrailDecision = {
      stage: 'request',
      index: null,
      verdict: ok ? 'allow' : read.verdict,
      category: ok ? null : (read.category ?? 'other'),
      reason: `Edited prompt: ${read.reason}`,
      model: message.model,
      at: now(),
    }
    row = await addDecisions(ctx, row.id, [decision], ok ? { prompt } : {}, costUsd)
    if (!ok)
      throw conflict(reasonOf({ ...read, category: decision.category }), {
        category: decision.category,
      })
  }

  const perImage = resolved.provider.perImageUsd(resolved.model, resolved.quality)
  await assertBudget(ctx, perImage * input.count)

  const refRows = row.referenceIds.length
    ? await ctx.repo.references.many({ where: inArray(t.reference.id, row.referenceIds) })
    : []
  const refs = row.referenceIds.flatMap((id) => {
    const r = refRows.find((x) => x.id === id)
    return r ? [toReference(r)] : []
  })
  const parentRow = row.parentId
    ? await ctx.repo.references.first(eq(t.reference.id, row.parentId))
    : undefined
  const parent = parentRow ? toReference(parentRow) : null
  // Rights are checked again: a reference may have become view-only since the brief.
  await assertSendable(
    ctx,
    [...refs, ...(parent ? [parent] : [])].flatMap((r) => (r.assetId ? [r.assetId] : [])),
  )
  const roleOf = (id: string) =>
    (row.roles.find((r) => r.id === id)?.role ?? null) as ProviderReference['role']
  const providerRefs: ProviderReference[] = []
  if (parent)
    providerRefs.push({ ...(await picture(ctx, parent, 'Parent image')).provider, role: 'subject' })
  for (const r of refs)
    providerRefs.push({ ...(await picture(ctx, r, r.title)).provider, role: roleOf(r.id) })

  const safetyId = createHash('sha256')
    .update(`${ctx.orgFingerprint}:${ctx.user.id}`)
    .digest('hex')
    .slice(0, 32)
  let result: Awaited<ReturnType<ImageProvider['generate']>>
  try {
    result = await resolved.provider.generate({
      apiKey: resolved.apiKey,
      model: resolved.model,
      prompt,
      references: providerRefs,
      count: input.count,
      aspect: row.aspect,
      quality: resolved.quality,
      ...(input.seed !== undefined ? { seed: input.seed } : {}),
      safetyId,
      ...(ctx.signal ? { signal: ctx.signal } : {}),
    })
  } catch (err) {
    if (ctx.signal?.aborted) throw ctx.signal.reason
    if (err instanceof ProviderError) throw providerFailure(err, resolved.provider)
    throw err
  }
  // Billed whether or not the images are kept: the provider made them.
  if (result.costUsd > 0 || result.images.length)
    await recordUsage(ctx, {
      meter: 'image',
      provider: resolved.provider.id,
      model: result.model,
      quantity: result.images.length + result.blocked.length,
      unit: 'images',
      costUsd: result.costUsd,
      idempotencyKey: `${genId}:image`,
      runId: claude.runId,
      pieceId: projectOf(board),
      stage: 'design',
    })
  for (const b of result.blocked)
    decisions.push({
      stage: 'provider',
      index: b.index,
      verdict: 'refuse',
      category: 'other',
      reason: b.reason,
      model: result.model,
      at: now(),
    })

  // Claude looks at every image before any is stored. Labelled 1..n in the provider's order.
  const kept: typeof result.images = []
  const refused: CommandOutput<'references.generate'>['refused'] = result.blocked.map((b) => ({
    index: b.index,
    category: 'other' as const,
    reason: b.reason,
  }))
  if (result.images.length) {
    const forClaude = await Promise.all(
      result.images.map(async (img, k) => {
        const m = await modelImage(img.bytes, img.mime)
        if (!m)
          throw conflict(
            `${resolved.provider.label} returned a ${img.mime} picture that cannot be checked`,
          )
        return { ...m, label: `Image ${k + 1}` }
      }),
    )
    let check: ReturnType<typeof parseCheckMessage>
    let checkModel: string = claude.model
    try {
      const { message, costUsd } = await ask(
        ctx,
        claude,
        buildCheckRequest({
          model: claude.model,
          request: row.request,
          prompt,
          images: forClaude,
          attested,
        }),
        `${genId}:check`,
        board,
      )
      claudeUsd += costUsd
      checkModel = message.model
      check = parseCheckMessage(message, result.images.length)
    } catch (err) {
      if (!(err instanceof GuardError) && !(err instanceof AppError)) throw err
      if (err instanceof GuardError && err.code === 'refusal')
        check = {
          images: result.images.map((_, k) => ({
            index: k + 1,
            verdict: 'refuse' as const,
            category: 'other' as const,
            reason: 'Claude declined to look at this image, so it was not kept.',
          })),
        }
      else {
        // The check could not run: fail closed, keep nothing, and say what was spent.
        await addDecisions(
          ctx,
          row.id,
          [
            ...decisions,
            {
              stage: 'image',
              index: null,
              verdict: 'refuse',
              category: 'other',
              reason: `The safety check could not run (${err.message}); no image was kept.`,
              model: claude.model,
              at: now(),
            },
          ],
          {},
          claudeUsd,
        )
        throw conflict(
          `The safety check of the images could not run, so none was kept (${err.message}). The provider’s charge for them still applies.`,
        )
      }
    }
    for (const [k, verdict] of check.images.entries()) {
      const img = result.images[k]!
      decisions.push({
        stage: 'image',
        index: img.index,
        verdict: verdict.verdict,
        category: verdict.verdict === 'allow' ? null : (verdict.category ?? 'other'),
        reason: verdict.reason,
        model: checkModel,
        at: now(),
      })
      if (verdict.verdict === 'allow' && !(verdict.category === 'trademark' && !attested))
        kept.push(img)
      else
        refused.push({
          index: img.index,
          category: verdict.category ?? 'other',
          reason: reasonOf({
            verdict: 'refuse',
            category: verdict.category ?? 'other',
            reason: verdict.reason,
          }),
        })
    }
  }

  // Only now, with every kept image checked, does anything reach storage.
  const inputs = [...(parent ? [parent] : []), ...refs].map((p) => ({
    id: p.id,
    role: p.id === parent?.id ? ('subject' as const) : roleOf(p.id),
    title: p.title,
    provider: p.source?.provider ?? null,
    url: p.source?.url ?? null,
    credit: p.source?.credit ?? null,
    license: p.source?.license ?? null,
    rights: p.rights,
  }))
  const items: NewReference[] = []
  for (const img of kept) {
    const ext = img.mime === 'image/jpeg' ? 'jpg' : img.mime === 'image/webp' ? 'webp' : 'png'
    const asset = await putAsset(ctx, {
      bytes: img.bytes,
      name: `generated-${genId}-${img.index}.${ext}`,
      mime: img.mime,
      kind: 'image',
    })
    items.push({
      type: 'generated',
      assetId: asset.id,
      title: `${(row.understanding || row.request).slice(0, 72)} (${img.index})`,
      source: {
        provider: resolved.provider.id,
        url: null,
        credit: `Generated with ${resolved.provider.label} (${result.model})`,
        license: null,
        licenseUrl: null,
        capturedAt: asset.createdAt,
      },
      rights: 'own',
      generation: {
        prompt,
        request: row.request,
        briefId: row.id,
        provider: resolved.provider.id,
        model: result.model,
        seed: input.seed ?? null,
        costUsd: img.costUsd,
        parentIds: [...(parent ? [parent.id] : []), ...refs.map((r) => r.id)],
        inputs,
        runId: claude.runId,
      },
      width: asset.width,
      height: asset.height,
    })
  }
  const references = items.length ? await insertReferences(ctx, board.id, items) : []
  row = await addDecisions(
    ctx,
    row.id,
    decisions,
    { generations: sql`${t.imageBrief.generations} + 1` as unknown as number },
    claudeUsd,
  )
  const notes = [...result.notes]
  if (refused.length)
    notes.push(
      `${refused.length} of ${input.count} images ${refused.length === 1 ? 'was' : 'were'} refused and not kept.`,
    )
  return {
    brief: await present(ctx, row),
    references,
    refused: refused.sort((a, b) => a.index - b.index),
    provider: resolved.provider.id,
    model: result.model,
    cost: { imageUsd: result.costUsd, claudeUsd, estimated: result.estimated },
    notes,
  }
}

/** The briefs of a board, newest first (the generate panel's history). */
export async function boardBriefs(ctx: Ctx, boardId: string, limit = 20): Promise<ImageBrief[]> {
  await getBoard(ctx, boardId)
  const rows = await ctx.repo.imageBriefs.many({
    where: eq(t.imageBrief.boardId, boardId),
    orderBy: desc(t.imageBrief.createdAt),
    limit,
  })
  return Promise.all(rows.map((r) => present(ctx, r)))
}
