/**
 * Concept images on the design board, from a person's words and board pictures to four images:
 *
 *   references.brief     Claude reads the request and the pictures it names, decides whether Pavé
 *                        may make it (the guardrail), and writes the prompt enhanced for jewelry.
 *                        Stored as an `image_brief`, the trace every later decision is added to.
 *   references.attestBrief  A person (never the assistant) attests the right to use a brand or
 *                        design the guardrail named; that lifts `needs_rights`.
 *   references.generate  The provider makes the images from exactly the brief's prompt (an edited
 *                        prompt is checked again first). Claude looks at every image; a refused
 *                        one is never stored. The rest become board items with their lineage.
 *
 * Inside an assistant run the Claude calls use the run's client and tier (`ctx.claude`) and are
 * billed to the run; outside, the organisation's default tier. Claude's spend is metered on the
 * `llm` meter and the provider's on `image`, both as Design work on the board's project. Every
 * failure of the guardrail fails closed: nothing unchecked is ever kept.
 */
