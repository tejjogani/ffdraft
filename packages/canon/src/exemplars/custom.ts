/** Custom ring exemplars: research 09 §1 "Toi-et-moi" and §5 Art Nouveau / nature. */
import { exemplar, us } from './define'

/** A point on the band surface: φ degrees round from the top, y along the finger. */
const R = 10.4
const onBand = (phi: number, y: number): [number, number, number] => {
  const a = (phi * Math.PI) / 180
  return [Number((R * Math.sin(a)).toFixed(3)), y, Number((R * Math.cos(a)).toFixed(3))]
}

